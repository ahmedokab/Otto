function vehicleYears(make, model) {
  const spec = VEHICLES[make]?.[model];
  if (!spec) return [];
  const out = [];
  for (const range of spec[0].split(',')) {
    const [a, b = a] = range.split('-').map(Number);
    for (let y = Math.max(a, 1996); y <= b; y++) out.push(String(y));
  }
  return out.reverse();   // newest first
}

function vehicleTrims(make, model) {
  return VEHICLES[make]?.[model]?.[1].split('|') || [];
}
